std::string toCSource(const EncodedFont& font, const WriterOptions& options)
{
    if (!isIdentifier(options.arrayName)) {
        throw EncodeError("C array name is not a valid identifier");
    }
    validateWriterOptions(options);
    validateFont(font);

    const std::size_t estimatedBytes =
        static_cast<std::size_t>(font.recordSize) * font.glyphs.size() * 8 + 512;
    if (estimatedBytes > kMaxCSourceBytes) {
        throw EncodeError("C source would exceed the 64 MiB safety limit; use BIN output");
    }

    std::string out;
    out.reserve(estimatedBytes);

    out += "// Generated by FontMaker.\n";
    out += "// " + std::to_string(font.glyphs.size()) + " glyphs, "
        + std::to_string(font.width) + "x" + std::to_string(font.height) + " px, "
        + toString(font.options.scan) + ", " + toString(font.options.bitOrder) + ", "
        + (font.options.variableWidth ? "variable width" : "fixed width") + ".\n";
    out += "static const unsigned char " + options.arrayName + "[]["
        + std::to_string(font.recordSize) + "] =\n{\n";

    for (const auto& glyph : font.glyphs) {
        out += "    { // ";
        out += codepointLabel(glyph.codepoint);
        if (!glyph.note.empty()) {
            out += " (";
            out += glyph.note;
            out += ')';
        } else if (isCommentPrintable(glyph.codepoint) && glyph.codepoint != U'\'') {
            out += " '";
            out += utf8Encode(glyph.codepoint);
            out += "'";
        }
        out += "\n";

        for (std::size_t index = 0; index < glyph.bytes.size(); ++index) {
            if (index % options.bytesPerLine == 0) {
                out += "        ";
            }
            out += hexByte(glyph.bytes[index]);
            out += ',';
            if ((index + 1) % options.bytesPerLine == 0 || index + 1 == glyph.bytes.size()) {
                out += '\n';
            } else {
                out += ' ';
            }
        }
        out += "    },\n";
    }

    out += "};\n";
    return out;
}

std::vector<std::uint8_t> toBinary(const EncodedFont& font)
{
    validateFont(font);
    std::vector<std::uint8_t> result;
    result.reserve(static_cast<std::size_t>(font.recordSize) * font.glyphs.size());
    for (const auto& glyph : font.glyphs) {
        result.insert(result.end(), glyph.bytes.begin(), glyph.bytes.end());
    }
    return result;
}

void saveFont(
    const std::filesystem::path& path,
    const EncodedFont& font,
    OutputFormat format,
    const WriterOptions& options)
{
    if (format == OutputFormat::CSource) {
        const std::string source = toCSource(font, options);
        writeBinaryFile(path, std::span<const std::uint8_t>(
            reinterpret_cast<const std::uint8_t*>(source.data()), source.size()));
    } else {
        const auto bytes = toBinary(font);
        writeBinaryFile(path, bytes);
    }
}

